<script lang="ts">
	import { enhance } from '$app/forms';
	import { m } from '#lib/paraglide/messages.js';
	import { canManageStock, hasRole } from '#lib/roles.ts';
	import { selection } from '#lib/selection.svelte.ts';
	import BoxFields from '#lib/components/BoxFields.svelte';
	import ItemCard from '#lib/components/ItemCard.svelte';
	import { kindLabel, KIND_ICONS } from '#lib/format.ts';
	import type { PageProps } from './$types';

	let { data, form }: PageProps = $props();

	const box = $derived(data.box);
	const keeper = $derived(canManageStock(data.user?.role));
	let editing = $state(false);

	function confirmDelete(event: SubmitEvent) {
		if (!confirm(m.box_delete_confirm())) event.preventDefault();
	}
</script>

<svelte:head><title>{box.label}</title></svelte:head>

<div class="mb-6 flex flex-col gap-4 md:flex-row md:items-start">
	<div class="flex-1">
		<p class="text-sm text-stone-500">
			{KIND_ICONS[box.kind]}
			{kindLabel(box.kind)} · {box.container.name}{box.shelf ? ` · ${box.shelf}` : ''}
		</p>
		<h1>{box.label}</h1>
		<p class="mt-1 font-mono text-stone-500">{box.code}</p>
		{#if box.description}<p class="mt-2 text-stone-700">{box.description}</p>{/if}
		<div class="mt-4 flex flex-wrap gap-2">
			{#if data.items.length}
				<button
					type="button"
					class="btn"
					onclick={() => selection.add(...data.items.map((i) => i.id))}
				>
					{m.selection_add_all()}
				</button>
			{/if}
			<a class="btn" href="/map?box={box.id}">{m.map_open()}</a>
			{#if keeper}
				<a class="btn" href="/items/new?box={box.id}">+ {m.item_new()}</a>
				<a class="btn" href="/labels?boxes={box.id}">{m.labels_print()}</a>
				<button type="button" class="btn" onclick={() => (editing = !editing)}
					>{m.action_edit()}</button
				>
			{/if}
		</div>
	</div>
	<!-- eslint-disable-next-line svelte/no-at-html-tags -- QR SVG generated by the server -->
	<div class="card h-36 w-36 shrink-0 p-2">{@html data.qr}</div>
</div>

{#if editing || form?.invalid}
	<form
		method="POST"
		action="?/update"
		use:enhance={() =>
			async ({ update, result }) => {
				await update({ reset: false });
				if (result.type === 'success') editing = false;
			}}
		class="card mb-6 flex flex-col gap-3 p-4"
	>
		<BoxFields
			values={form?.values ?? {
				label: box.label,
				kind: box.kind,
				description: box.description,
				shelf: box.shelf,
				widthCm: box.widthCm,
				depthCm: box.depthCm,
				heightCm: box.heightCm,
				posXCm: box.posXCm,
				posYCm: box.posYCm,
				posZCm: box.posZCm
			}}
		/>
		{#if form?.invalid}<p class="text-sm text-red-700">{m.form_invalid()}</p>{/if}
		<div class="flex gap-2">
			<button class="btn btn-primary">{m.action_save()}</button>
		</div>
	</form>
	{#if hasRole(data.user?.role, 'ADMIN')}
		<form method="POST" action="?/delete" use:enhance onsubmit={confirmDelete} class="mb-6">
			<button class="btn btn-danger">{m.box_delete()}</button>
			{#if form?.notEmpty}<p class="mt-2 text-sm text-red-700">{m.box_delete_not_empty()}</p>{/if}
		</form>
	{/if}
{/if}

<h2 class="mb-3">{m.box_contents({ count: data.items.length })}</h2>
{#if data.items.length}
	<div class="grid grid-cols-2 gap-3 sm:grid-cols-3 lg:grid-cols-5">
		{#each data.items as item (item.id)}<ItemCard {item} selectable />{/each}
	</div>
{:else}
	<p class="card p-8 text-center text-stone-500">{m.box_empty()}</p>
{/if}
